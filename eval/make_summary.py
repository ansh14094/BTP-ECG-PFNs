#!/usr/bin/env python3
"""Generate paper/RESULTS_SUMMARY.md from the final numbers only.

Every sentence here is produced by comparing values read out of
`imbreg/results/metrics/all_metrics.csv`. The direction words ("reduces",
"increases") are chosen by the sign of the measured difference, not written by
hand, so a sentence cannot drift from its data -- including where the method does
worse, which the plan explicitly asks to be stated.

Cells with no data produce a "not available" line rather than being skipped, so a
missing run is visible in the summary instead of silently absent.

    python3 eval/make_summary.py
"""
from __future__ import annotations

import glob
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MET = os.path.join(ROOT, "imbreg", "results", "metrics", "all_metrics.csv")
SIG = os.path.join(ROOT, "imbreg", "results", "metrics", "significance.csv")
OUT = os.path.join(ROOT, "paper", "RESULTS_SUMMARY.md")
SEEDS = range(5)
LR_SWEPT = {"ft_gauss", "ft_uniform", "ticl_ft_gauss", "ticl_ft_uniform"}


def best_tags() -> dict:
    best: dict = {}
    for f in glob.glob(os.path.join(ROOT, "imbreg", "results", "*.jsonl")):
        for line in open(f):
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            if "arm" not in r or r.get("val_rmse") is None:
                continue
            k = (r.get("dataset"), r.get("protocol"), r["arm"], int(r.get("seed", -1)))
            if k not in best or float(r["val_rmse"]) < best[k][0]:
                best[k] = (float(r["val_rmse"]), r.get("tag"))
    return {k: t for k, (_, t) in best.items()}


BEST = best_tags()


def val(df, ds, proto, arm, metric):
    sub = df[(df.dataset == ds) & (df.protocol == proto) & (df.arm == arm)]
    if sub.empty or metric not in sub.columns:
        return None
    vals = []
    for s in SEEDS:
        rows = sub[sub.seed == s]
        if rows.empty:
            continue
        if len(rows) > 1 and arm in LR_SWEPT:
            t = BEST.get((ds, proto, arm, s))
            if t is not None and (rows.tag == t).any():
                rows = rows[rows.tag == t]
        v = rows[metric].to_numpy(float)
        v = v[np.isfinite(v)]
        if len(v):
            vals.append(float(v[0]))
    return float(np.mean(vals)) if vals else None


def direction(new, ref, nd=3):
    """'reduces X from a to b' / 'increases X from a to b', chosen by the sign."""
    if new is None or ref is None:
        return None
    word = "reduces" if new < ref else "increases"
    return f"{word} it from {ref:.{nd}f} to {new:.{nd}f}"


DS = [("Abalone", "abalone", 3), ("Communities", "communities", 4),
      ("Wine Quality White", "wine_white", 3)]


def main() -> None:
    df = pd.read_csv(MET)
    L = ["# Results summary",
         "",
         "Every sentence below is generated by `eval/make_summary.py` from",
         "`imbreg/results/metrics/all_metrics.csv`. Direction words follow the sign of",
         "the measured difference. Cases where the method does worse are included.",
         ""]

    # --- Table 1a -----------------------------------------------------------
    L += ["## Table 1a — TabICL, synthetic-prior continued pre-training", ""]
    for metric, nice in [("mae_few", "few-shot MAE"), ("mae", "overall MAE")]:
        better = []
        for title, ds, nd in DS:
            g = val(df, ds, "dir", "ticl_prior_gauss", metric)
            u = val(df, ds, "dir", "ticl_prior_uniform", metric)
            if g is None or u is None:
                L.append(f"- {title}: {nice} not available.")
                continue
            better.append(g < u)
            L.append(f"- {title}: against its matched uniform control, Gaussian "
                     f"context {direction(g, u, nd)} ({nice}).")
        if better:
            n = sum(better)
            L.append(f"- Gaussian context improves {nice} on {n} of {len(better)} "
                     f"tabular datasets.")
        L.append("")
    for title, ds, nd in DS:
        t = val(df, ds, "dir", "ticl_prior_target_balanced", "mae_few")
        g = val(df, ds, "dir", "ticl_prior_gauss", "mae_few")
        if t is None:
            L.append(f"- {title}: target-balanced context not available.")
        else:
            w = "better" if g < t else "worse"
            L.append(f"- {title}: Gaussian few-shot MAE {g:.{nd}f} is {w} than "
                     f"target-balanced {t:.{nd}f}.")
    L.append("")

    # --- Table 1b -----------------------------------------------------------
    L += ["## Table 1b — TabPFN-2.5, per-dataset fine-tuning", ""]
    for title, ds, nd in DS:
        g = val(df, ds, "dir", "ft_gauss", "mae_few")
        u = val(df, ds, "dir", "ft_uniform", "mae_few")
        if g is None or u is None:
            L.append(f"- {title}: not available.")
            continue
        L.append(f"- {title}: against uniform fine-tuning, Gaussian fine-tuning "
                 f"{direction(g, u, nd)} (few-shot MAE).")
    L.append("")

    # --- Table 2 ------------------------------------------------------------
    L += ["## Table 2 — PTB-XL age prediction, official test split", ""]
    rn = val(df, "ptbxl_resnet", "fixed", "vanilla", "mae")
    for label, ds, arm in [("E3 + stock TabICL", "ptbxl_enc_e3", "ticl_zeroshot"),
                           ("E3 + Gaussian TabICL", "ptbxl_enc_e3", "ticl_prior_gauss"),
                           ("E2 + Gaussian TabPFN", "ptbxl_tabpfn_enc", "ft_gauss")]:
        v = val(df, ds, "fixed", arm, "mae")
        if v is None:
            L.append(f"- {label}: not available.")
        elif rn is None:
            L.append(f"- {label}: natural MAE {v:.3f} years "
                     f"(ResNet baseline not available).")
        else:
            w = "below" if v < rn else "above"
            L.append(f"- {label}: natural MAE {v:.3f} years, {w} the ResNet "
                     f"vanilla baseline at {rn:.3f}.")
    g = val(df, "ptbxl_enc_e3", "fixed", "ticl_prior_gauss", "mae_old")
    s = val(df, "ptbxl_enc_e3", "fixed", "ticl_zeroshot", "mae_old")
    gm_ = val(df, "ptbxl_enc_e3", "fixed", "ticl_prior_gauss", "mae_middle")
    sm = val(df, "ptbxl_enc_e3", "fixed", "ticl_zeroshot", "mae_middle")
    if None not in (g, s, gm_, sm):
        L.append(f"- The trade-off, E3: Gaussian context {direction(g, s)} in the "
                 f"age>=60 band and {direction(gm_, sm)} in the 30-60 band.")
    L.append("")

    # --- Table 3 ------------------------------------------------------------
    L += ["## Table 3 — encoder against prediction head", ""]
    for label, ds in [("E1", "ptbxl_l1_enc"), ("E2", "ptbxl_tabpfn_enc"),
                      ("E3", "ptbxl_enc_e3"), ("E4", "ptbxl_enc_e4")]:
        n_s = val(df, ds, "fixed", "ticl_zeroshot", "mae")
        n_g = val(df, ds, "fixed", "ticl_prior_gauss", "mae")
        b_s = val(df, ds, "dir", "ticl_zeroshot", "mae")
        b_g = val(df, ds, "dir", "ticl_prior_gauss", "mae")
        if n_s is None or n_g is None:
            L.append(f"- {label}: clean-split results not available.")
        else:
            L.append(f"- {label}: on the official split the Gaussian head "
                     f"{direction(n_g, n_s)}.")
        if None not in (b_s, b_g, n_s, n_g):
            L.append(f"  On the balanced split the same pair reads {b_s:.3f} and "
                     f"{b_g:.3f}; the balanced split re-uses encoder training data "
                     f"(see results/STATUS.md) and is optimistic by roughly 0.7 years.")
    L.append("")

    # --- significance -------------------------------------------------------
    if os.path.exists(SIG):
        sg = pd.read_csv(SIG)
        ok = sg[sg.status == "ok"] if "status" in sg.columns else sg.iloc[0:0]
        L += ["## Significance (paired bootstrap, 10,000 resamples)", ""]
        if ok.empty:
            L.append("- No comparison has both arms available yet.")
        for _, r in ok.iterrows():
            verdict = ("excludes zero" if r.get("significant") else "includes zero")
            L.append(f"- {r['comparison']} [{r['band']}]: dMAE {r['delta_mae']:+.3f}, "
                     f"95% CI [{r['ci_lo']:+.3f}, {r['ci_hi']:+.3f}] ({verdict}), "
                     f"wins {int(r['wins'])}/{int(r['n_seeds'])} seeds.")
        L.append("")

    with open(OUT, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", OUT)
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
